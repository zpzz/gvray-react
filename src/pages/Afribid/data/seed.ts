function buildHomeSamples(): Vehicle[] {
  return HOME_SAMPLE_ROWS.map(
    ([id, base, kind, year, model, price, country, city, mileage], index) => {
      const source = BASE_VEHICLES.find((v) => v.id === base)!;
      const starts = new Date();
      starts.setUTCDate(starts.getUTCDate() + 7 + (index % 6));
      starts.setUTCHours(12 + (index % 3), 0, 0, 0);
      return {
        ...source,
        id,
        year,
        model,
        price,
        country,
        city,
        mileage,
        mode: kind === 'auction' ? 'auction' : 'direct',
        status: kind === 'auction' ? 'Upcoming' : 'Available',
        deposit: kind === 'auction' ? 100000 : 0,
        startPrice: kind === 'auction' ? price ?? undefined : undefined,
        starts: kind === 'auction' ? starts.toISOString() : undefined,
        saleCountries: [...new Set([country, ...source.saleCountries])],
        firstRegistration: `${year}-06-12`,
        vin: `DEMO${id.replace('-', '')}0000000`.slice(0, 17),
      };
    },
  );
}

